-- Single-shop MVP schema. Keep the stable shop id centralized for later settings joins.
CREATE TABLE public.products (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  shop_id uuid NOT NULL DEFAULT '00000000-0000-4000-8000-000000000001',
  name text NOT NULL,
  aliases text[] NOT NULL DEFAULT '{}',
  description text NOT NULL DEFAULT '',
  image_url text,
  price numeric(10, 2) NOT NULL CHECK (price >= 0),
  active boolean NOT NULL DEFAULT true,
  discount_type text CHECK (discount_type IN ('percent', 'fixed')),
  discount_value numeric(10, 2) CHECK (discount_value IS NULL OR discount_value >= 0),
  discount_starts timestamptz,
  discount_ends timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.variants (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  size text NOT NULL DEFAULT 'One size',
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  UNIQUE (product_id, size)
);

CREATE TABLE public.promos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  label text NOT NULL,
  kind text NOT NULL CHECK (kind = 'qty_percent'),
  min_qty integer NOT NULL CHECK (min_qty >= 2),
  value numeric(10, 2) NOT NULL CHECK (value > 0 AND value <= 100),
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean NOT NULL DEFAULT true
);

CREATE TABLE public.customers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  channel text NOT NULL,
  external_id text NOT NULL,
  name text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (channel, external_id)
);

CREATE TABLE public.conversations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id uuid NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'needs_seller', 'resolved')),
  ai_mode text NOT NULL DEFAULT 'auto' CHECK (ai_mode IN ('auto', 'suggest', 'human')),
  pending jsonb NOT NULL DEFAULT '{}'::jsonb,
  context_product_id uuid REFERENCES public.products(id) ON DELETE SET NULL,
  last_message_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  conversation_id uuid NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  sender text NOT NULL CHECK (sender IN ('customer', 'ai', 'seller', 'system')),
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1042) PRIMARY KEY,
  conversation_id uuid NOT NULL REFERENCES public.conversations(id) ON DELETE RESTRICT,
  customer_id uuid NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
  total numeric(10, 2) NOT NULL CHECK (total >= 0),
  shipping numeric(10, 2) NOT NULL DEFAULT 0 CHECK (shipping >= 0),
  status text NOT NULL DEFAULT 'awaiting_payment' CHECK (status IN ('awaiting_payment', 'paid', 'shipped')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.order_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  variant_id uuid NOT NULL REFERENCES public.variants(id) ON DELETE RESTRICT,
  qty integer NOT NULL CHECK (qty > 0),
  unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
  offer_label text
);

CREATE TABLE public.missed_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_text text NOT NULL,
  conversation_id uuid NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.ai_usage (
  day date PRIMARY KEY,
  count integer NOT NULL DEFAULT 0 CHECK (count >= 0)
);

CREATE TABLE public.shop_settings (
  shop_id uuid PRIMARY KEY DEFAULT '00000000-0000-4000-8000-000000000001',
  shipping_rates jsonb NOT NULL DEFAULT '{}'::jsonb,
  payment_instructions text NOT NULL DEFAULT '',
  policies text NOT NULL DEFAULT ''
);

CREATE FUNCTION public.reserve_stock(p_variant uuid, p_qty integer)
RETURNS boolean
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  updated_rows integer;
BEGIN
  IF p_qty IS NULL OR p_qty <= 0 THEN
    RETURN false;
  END IF;

  UPDATE public.variants
  SET stock = stock - p_qty
  WHERE id = p_variant AND stock >= p_qty;

  GET DIAGNOSTICS updated_rows = ROW_COUNT;
  RETURN updated_rows = 1;
END;
$$;

